# run-on.sh — launch a nested compositor into a CDE scratch workspace (plans/harness-run-on-2026-11.md).
# Sourced by the bash drivers (g1, g2, spike-mem, g3); bash + coreutils only. Builds a per-launch bash wrapper with printf %q.
#
#   . "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../lib/run-on.sh"     # captures the LIVE CDE_SOCKET here, before any driver override
#   run_on_launch g3 "$T" "$T/log" XDG_RUNTIME_DIR="$T/run" -- "$BIN" --winit || fail   # pid in $RUN_ON_PID
#   run_on_close "$pid"                                                       # live `crucible msg close-pid`, never fails
#
# run_on_launch DRIVER DIR OUT [NAME=value ...] -- CMD [ARG ...]
#   DRIVER   g1 | g2 | spike-mem | g3 (workspace ${CTERM_SCRATCH_WS:-scratch-cterm-DRIVER-$$}; an override must start with `scratch-`)
#   DIR      caller scratch dir that receives the wrapper script (run-on.<n>.sh)
#   OUT      stdout+stderr target: a file, a FIFO (its reader must already be running), or `>>file` to append
#   NAME=..  env words (vblank_mode=0 is always set); CMD ARG ... the command, exec'd by the wrapper
# The wrapper cds to the caller's $PWD, takes stdin from /dev/null, closes fds 3-63 and execs the command, so the
# pid run-on reports (`ok <pid>`) names the exec'd program. Returns 0 with the pid in $RUN_ON_PID; otherwise prints a
# reason on stdout and returns 1 (unset/empty live CDE_SOCKET, a bad workspace name, or a reply that is not `ok <digits>`).
# It never launches any other way. run-on, close-pid and the live socket are the live `crucible` on PATH, never the driver's $BIN.

# >>> shguard modes=source (generated by shell-disposition-gate --guard; do not edit)
case $(realpath -- "$0" 2>/dev/null) in */'scripts/lib/run-on.sh') _shguard_m='exec' ;; *) if [ "${SHGUARD_MODE-}" = 'pipe' ]; then _shguard_m='pipe'; else _shguard_m='source'; fi ;; esac
# shellcheck disable=SC2317
case $_shguard_m in
  source) unset _shguard_m ;;
  *) printf '%s: refusing %s invocation (supports: source; pipe callers set SHGUARD_MODE=pipe)\n' 'run-on.sh' "$_shguard_m" >&2; unset _shguard_m; return 1 2>/dev/null || exit 1 ;;
esac
# <<< shguard
set -euo pipefail
RUN_ON_LIVE_SOCK=${CDE_SOCKET-}
RUN_ON_PID=""
RUN_ON_N=0

# run_on_ws DRIVER: print the workspace name, or return 1 when a CTERM_SCRATCH_WS override does not start with `scratch-`
run_on_ws() {
	local ws=${CTERM_SCRATCH_WS:-scratch-cterm-$1-$$}
	case $ws in scratch-?*) printf '%s\n' "$ws" ;; *) return 1 ;; esac
}

# run_on_reply_pid REPLY: print the pid of an exact `ok <digits>` reply, else return 1
run_on_reply_pid() {
	case $1 in
	ok\ *[!0-9]* | ok\ | ok) return 1 ;;
	ok\ [0-9]*) printf '%s\n' "${1#ok }" ;;
	*) return 1 ;;
	esac
}

# shellcheck disable=SC2034 # RUN_ON_PID is read by the sourcing driver
run_on_launch() {
	local driver=$1 dir=$2 out=$3 ws w word redir=">" reply
	shift 3
	RUN_ON_PID=""
	[ -n "$RUN_ON_LIVE_SOCK" ] || { echo "HARNESS FAILURE: run-on: CDE_SOCKET is unset or empty (the live CDE socket); not launching"; return 1; }
	ws=$(run_on_ws "$driver") || { echo "HARNESS FAILURE: run-on: CTERM_SCRATCH_WS must start with scratch- (got '${CTERM_SCRATCH_WS-}')"; return 1; }
	case $out in '>>'*) redir=">>" out=${out#'>>'} ;; esac
	RUN_ON_N=$((RUN_ON_N + 1))
	w=$dir/run-on.$RUN_ON_N.sh
	{
		echo '#!/bin/bash'
		printf 'cd -- %q || exit 1\n' "$PWD"
		echo 'export vblank_mode=0'
		while [ "$#" -gt 0 ]; do
			word=$1
			shift
			[ "$word" != -- ] || break
			case $word in [A-Za-z_]*=*) printf 'export %s=%q\n' "${word%%=*}" "${word#*=}" ;; *) echo "HARNESS FAILURE: run-on: bad env word '$word'" >&2; return 1 ;; esac
		done
		echo 'for f in $(seq 3 63); do eval "exec $f>&-"; done'
		echo 'exec </dev/null'
		printf 'exec %s %q 2>&1\n' "$redir" "$out"
		# own session like the old `setsid CMD &`; setsid forks (and run-on would report the parent's pid) only when the caller is a
		# process-group leader, which a run-on child is not (measured), so it is used only when the group id differs from our pid
		echo 'read -ra st </proc/$$/stat'
		printf 'if [ "${st[4]}" = "$$" ]; then exec'
		printf ' %q' "$@"
		printf '; else exec setsid'
		printf ' %q' "$@"
		printf '; fi\n'
	} >"$w" || { echo "HARNESS FAILURE: run-on: cannot write $w"; return 1; }
	[ "$#" -gt 0 ] || { echo "HARNESS FAILURE: run-on: no command"; return 1; }
	chmod +x "$w"
	reply=$(CDE_SOCKET=$RUN_ON_LIVE_SOCK crucible msg run-on "$ws" "$w" 2>&1) || true
	RUN_ON_PID=$(run_on_reply_pid "$reply") || { RUN_ON_PID=""; echo "HARNESS FAILURE: run-on: unexpected reply '$reply'"; return 1; }
	return 0
}

# run_on_close PID: ask the live CDE to close every window of PID (the compositor's own pid); best effort
run_on_close() {
	[ -n "$RUN_ON_LIVE_SOCK" ] && [ -n "${1:-}" ] || return 0
	CDE_SOCKET=$RUN_ON_LIVE_SOCK crucible msg close-pid "$1" >/dev/null 2>&1 || true
	return 0
}
